function toneAgent(text) {
  const normalizedText = normalize(text);
  const supportive = ["ممتاز", "احسنت", "لا تقلق", "بهدوء", "ساشرح", "رائع", "تمام", "جيد", "good", "great", "well done"];
  const urgent = ["فورا", "حالاً", "عاجل", "اليوم", "قبل نهاية", "ضروري", "important", "urgent", "today"];
  const firm = ["مرفوض", "خطأ", "تاخرت", "لن", "لا يمكن", "يجب عليك", "wrong", "must", "rejected"];

  const score = (words) => words.reduce((sum, word) => sum + (normalizedText.includes(normalize(word)) ? 1 : 0), 0);
  const firmScore = score(firm) + (text.includes("!!") ? 1 : 0);
  const urgentScore = score(urgent);
  const supportiveScore = score(supportive);

  if (firmScore > 0) return { type: "firm", label: "صارمة" };
  if (urgentScore > 0) return { type: "urgent", label: "مستعجلة" };
  if (supportiveScore > 0) return { type: "supportive", label: "مشجعة وهادئة" };
  return { type: "neutral", label: "محايدة" };
}

