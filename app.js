function stabilizeLetterPrediction(prediction) {
  if (!prediction?.topPredictions?.length) return prediction;

  const currentLetters = new Set();
  for (const item of prediction.topPredictions) {
    const key = item.arabicLetter;
    const previousScore = letterScoreEma.get(key) || 0;
    const currentScore = Number(item.confidence) || 0;
    currentLetters.add(key);
    letterScoreEma.set(key, previousScore * (1 - LETTER_EMA_ALPHA) + currentScore * LETTER_EMA_ALPHA);
  }

  for (const [key, score] of letterScoreEma) {
    if (currentLetters.has(key)) continue;
    const decayedScore = score * LETTER_SCORE_DECAY;
    if (decayedScore < 0.01) {
      letterScoreEma.delete(key);
    } else {
      letterScoreEma.set(key, decayedScore);
    }
  }

  const ranked = Array.from(letterScoreEma.entries()).sort((first, second) => second[1] - first[1]);
  const [stableLetter, stableScore = 0] = ranked[0] || [];
  const stableMargin = stableScore - (ranked[1]?.[1] || 0);

  if (!stableLetter) return prediction;

  const stableTopPrediction = prediction.topPredictions.find((item) => item.arabicLetter === stableLetter);
  if (!stableTopPrediction) {
    return {
      ...prediction,
      stableScore: Number(stableScore.toFixed(4)),
      stableMargin: Number(stableMargin.toFixed(4)),
    };
  }

  const blendedConfidence = stableLetter === prediction.arabicLetter
    ? prediction.confidence * 0.72 + stableScore * 0.28
    : stableTopPrediction.confidence * 0.58 + stableScore * 0.42;

  return {
    ...prediction,
    ...stableTopPrediction,
    confidence: Number(clamp(blendedConfidence, 0, 0.99).toFixed(4)),
    margin: Number(Math.max(prediction.margin || 0, stableMargin * 0.72).toFixed(4)),
    stableScore: Number(stableScore.toFixed(4)),
    stableMargin: Number(stableMargin.toFixed(4)),
  };
}

