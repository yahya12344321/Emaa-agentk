function normalizeHandLandmarks(landmarks) {
  const wrist = landmarks[0];
  let minX = Infinity;
  let maxX = -Infinity;
  let minY = Infinity;
  let maxY = -Infinity;
  let minZ = Infinity;
  let maxZ = -Infinity;

  for (const point of landmarks) {
    const z = point.z || 0;
    minX = Math.min(minX, point.x);
    maxX = Math.max(maxX, point.x);
    minY = Math.min(minY, point.y);
    maxY = Math.max(maxY, point.y);
    minZ = Math.min(minZ, z);
    maxZ = Math.max(maxZ, z);
  }

  const scale = Math.max(
    maxX - minX,
    maxY - minY,
    maxZ - minZ,
    0.08,
  );

  const vector = new Array(Math.min(landmarks.length, HAND_LANDMARK_COUNT) * 3);
  for (let index = 0; index < vector.length / 3; index += 1) {
    const point = landmarks[index];
    const offset = index * 3;
    vector[offset] = Number(((point.x - wrist.x) / scale).toFixed(5));
    vector[offset + 1] = Number(((point.y - wrist.y) / scale).toFixed(5));
    vector[offset + 2] = Number((((point.z || 0) - (wrist.z || 0)) / scale).toFixed(5));
  }
  return vector;
}

function flattenRawHandLandmarks(landmarks) {
  const vector = new Float32Array(HAND_VECTOR_SIZE);
  const count = Math.min(landmarks.length, HAND_LANDMARK_COUNT);

  for (let index = 0; index < count; index += 1) {
    const point = landmarks[index];
    const offset = index * 3;
    vector[offset] = point.x;
    vector[offset + 1] = point.y;
    vector[offset + 2] = point.z || 0;
  }

  return vector;
}

function flattenMirroredRawHandLandmarks(landmarks) {
  const vector = flattenRawHandLandmarks(landmarks);
  for (let index = 0; index < vector.length; index += 3) {
    vector[index] = 1 - vector[index];
  }
  return vector;
}

function mirrorRawHandVector(vector) {
  const mirrored = vector.slice();
  for (let index = 0; index < mirrored.length; index += 3) {
    mirrored[index] = 1 - mirrored[index];
  }
  return mirrored;
}

