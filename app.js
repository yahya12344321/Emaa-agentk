function buildReverseSignBlocks(text) {
  const tokens = String(text || "").match(/[\p{L}\p{N}]+/gu) || [];
  return tokens
    .map((token) => {
      const wordSign = findReverseWordSign(token);
      return {
        token,
        wordSign,
        letters: splitWordToSignLetters(token).map((letter) => ({
          letter,
          image: signImageForLetter(letter),
          verified: Boolean(signImageForLetter(letter)),
        })),
      };
    })
    .filter((block) => block.letters.length || block.wordSign);
}

function findReverseWordSign(word) {
  const normalizedWord = normalizeWordForSign(word);
  if (!normalizedWord) return null;

  const dictionaryMatch = REVERSE_SIGN_DICTIONARY.find((entry) =>
    entry.words.some((item) => normalizeWordForSign(item) === normalizedWord),
  );
  if (dictionaryMatch) {
    return {
      label: dictionaryMatch.label,
      glyph: dictionaryMatch.glyph,
      source: "قاموس",
    };
  }

  const signMatch = state.signs.find((sign) => {
    const fields = [sign.signName, sign.intent, sign.phraseAr, sign.phraseEn];
    return fields.some((field) => {
      const normalizedField = normalizeWordForSign(field);
      return normalizedField === normalizedWord || normalizedField.split(/\s+/).includes(normalizedWord);
    });
  });

  if (!signMatch) return null;
  return {
    label: signMatch.signName,
    source: "إشارة مدعومة",
  };
}

function splitWordToSignLetters(word) {
  const letters = [];
  const source = Array.from(String(word || "").trim());

  for (let index = 0; index < source.length; index += 1) {
    const current = source[index];
    const next = source[index + 1];
    if (current === "ل" && ["ا", "أ", "إ", "آ"].includes(next)) {
      letters.push("لا");
      index += 1;
      continue;
    }
    if (/[\p{L}\p{N}]/u.test(current)) letters.push(current);
  }

  return letters;
}

