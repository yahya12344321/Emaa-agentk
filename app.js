function pruneVisionSamples(samples) {
  const signCounts = new Map();
  const pruned = [];

  for (const sample of samples || []) {
    if (!sample?.signId || !Array.isArray(sample.vector)) continue;
    const currentCount = signCounts.get(sample.signId) || 0;
    if (currentCount >= MAX_SAMPLES_PER_SIGN) continue;
    signCounts.set(sample.signId, currentCount + 1);
    pruned.push(sample);
    if (pruned.length >= MAX_TOTAL_SAMPLES) break;
  }

  return pruned;
}

function upgradeTrainedModel(saved) {
  if (!saved) return null;
  if (Array.isArray(saved.signs) && saved.signs.length) {
    return saved;
  }

  if (Array.isArray(saved.centroids) && saved.centroids.length) {
    return {
      version: 2,
      createdAt: saved.createdAt || new Date().toISOString(),
      totalSamples: saved.totalSamples || saved.centroids.reduce((sum, item) => sum + (item.samples || 1), 0),
      signs: saved.centroids.map((item) => ({
        signId: item.signId,
        samples: item.samples || 1,
        centroid: item.vector,
        exemplars: [item.vector],
        meanDistance: 0,
        maxDistance: 0,
        acceptanceRadius: 0.24,
      })),
      needsRetrain: Boolean(saved.needsRetrain),
    };
  }

  return null;
}

