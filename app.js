function predictPretrainedLetterFromVector(vector) {
  if (!pretrainedLetterModel?.layers?.length) return null;
  const expectedInputSize = pretrainedLetterModel.layers[0].inputSize;
  if (expectedInputSize && vector.length !== expectedInputSize) return null;

  let activations = Float32Array.from(vector);

  for (const layer of pretrainedLetterModel.layers) {
    activations = denseForward(activations, layer);
  }

  const topPredictions = topPretrainedPredictions(activations, 4);

  return topPredictions[0]
    ? {
        ...topPredictions[0],
        margin: Number(((topPredictions[0].confidence || 0) - (topPredictions[1]?.confidence || 0)).toFixed(4)),
        topPredictions,
      }
    : null;
}

function topPretrainedPredictions(probabilities, limit = 4) {
  const topPredictions = [];

  for (let index = 0; index < probabilities.length; index += 1) {
    const confidence = probabilities[index];
    let insertAt = topPredictions.findIndex((item) => confidence > item.confidence);

    if (insertAt === -1) insertAt = topPredictions.length;
    if (insertAt >= limit) continue;

    topPredictions.splice(insertAt, 0, {
      className: pretrainedLetterModel.classes[index],
      arabicLetter: LETTERS_MAPPING[pretrainedLetterModel.classes[index]] || pretrainedLetterModel.classes[index],
      confidence,
    });

    if (topPredictions.length > limit) topPredictions.pop();
  }

  return topPredictions;
}

function scorePretrainedPrediction(prediction) {
  if (!prediction) return -Infinity;
  return (prediction.confidence || 0) + (prediction.margin || 0) * 0.65;
}

function predictBestPretrainedLetterFromVector(vector) {
  const rawPrediction = predictPretrainedLetterFromVector(vector);
  if (!rawPrediction) {
    const mirroredFallback = predictPretrainedLetterFromVector(mirrorRawHandVector(vector));
    return mirroredFallback ? { ...mirroredFallback, sourceOrientation: "mirrored" } : null;
  }

  const rawScore = scorePretrainedPrediction(rawPrediction);
  const rawIsWeak =
    (rawPrediction.margin || 0) < PRETRAINED_MIRROR_FALLBACK_MARGIN &&
    (rawPrediction.confidence || 0) < PRETRAINED_MIRROR_FALLBACK_CONFIDENCE;

  if (!rawIsWeak) {
    return { ...rawPrediction, sourceOrientation: "raw" };
  }

  const mirroredPrediction = predictPretrainedLetterFromVector(mirrorRawHandVector(vector));
  if (!mirroredPrediction) {
    return { ...rawPrediction, sourceOrientation: "raw" };
  }

  return scorePretrainedPrediction(mirroredPrediction) > rawScore
    ? { ...mirroredPrediction, sourceOrientation: "mirrored" }
    : { ...rawPrediction, sourceOrientation: "raw" };
}

