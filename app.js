async function captureAverageHandVector(frameCount, delayMs, mode = "normalized") {
  const vectors = [];
  const maxAttempts = Math.max(frameCount, 1) * MAX_CAPTURE_ATTEMPTS_MULTIPLIER;

  for (let attempts = 0; attempts < maxAttempts && vectors.length < frameCount; attempts += 1) {
    const landmarks = detectHandLandmarks();
    const quality = measureHandQuality(landmarks);
    const vector = quality >= MIN_CAPTURE_QUALITY_SCORE ? handVectorFromLandmarks(landmarks, mode, quality) : null;

    if (vector) vectors.push(vector);
    if (vectors.length < frameCount) await delay(delayMs);
  }

  if (vectors.length < Math.ceil(frameCount * MIN_CAPTURE_FRAME_RATIO)) {
    return null;
  }

  if (vectors.length < frameCount) {
    for (let index = vectors.length; index < frameCount; index += 1) {
      vectors.push(vectors[vectors.length - 1]);
    }
  }

  return averageVectors(vectors);
}

