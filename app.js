function measureHandQuality(landmarks) {
  if (!landmarks?.length || !landmarks[0]) return 0;

  let minX = Infinity;
  let maxX = -Infinity;
  let minY = Infinity;
  let maxY = -Infinity;
  for (const point of landmarks) {
    minX = Math.min(minX, point.x);
    maxX = Math.max(maxX, point.x);
    minY = Math.min(minY, point.y);
    maxY = Math.max(maxY, point.y);
  }

  const spanX = maxX - minX;
  const spanY = maxY - minY;
  const area = spanX * spanY;
  const wrist = landmarks[0];
  const fingertipIndices = [8, 12, 16, 20];
  let tipDistance = 0;
  let tipCount = 0;

  for (const index of fingertipIndices) {
    if (landmarks[index]) {
      tipDistance += pointDistance3D(wrist, landmarks[index]);
      tipCount += 1;
    }
  }

  const avgTipDistance = tipCount ? tipDistance / tipCount : 0;

  const spanScore = clamp(Math.max(spanX, spanY) / 0.34, 0, 1);
  const areaScore = clamp(area / 0.055, 0, 1);
  const spreadScore = clamp(avgTipDistance / 0.28, 0, 1);

  return Number((spanScore * 0.45 + areaScore * 0.35 + spreadScore * 0.2).toFixed(3));
}

function pointDistance3D(first, second) {
  return Math.sqrt(
    (first.x - second.x) ** 2 +
      (first.y - second.y) ** 2 +
      ((first.z || 0) - (second.z || 0)) ** 2,
  );
}

