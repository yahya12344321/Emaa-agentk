function resolveBackendOrigin() {
  if (window.location.protocol === "http:" || window.location.protocol === "https:") {
    const { hostname, port } = window.location;
    const isLocalComputer = hostname === "localhost" || hostname === "127.0.0.1" || hostname === "::1";
    if (isLocalComputer && port && port !== "8000") {
      return BACKEND_FALLBACK_ORIGIN;
    }
    return window.location.origin;
  }
  return BACKEND_FALLBACK_ORIGIN;
}

function resolveAssetUrl(path) {
  if (window.location.protocol === "http:" || window.location.protocol === "https:") {
    return new URL(path, window.location.href).toString();
  }
  return path;
}

function getOrCreateBackendClientId() {
  try {
    const saved = localStorage.getItem(BACKEND_CLIENT_ID_STORAGE_KEY);
    if (saved) return saved;

    const clientId = `emaa-${uid("CLT").toLowerCase()}`;
    localStorage.setItem(BACKEND_CLIENT_ID_STORAGE_KEY, clientId);
    return clientId;
  } catch (error) {
    return `emaa-${uid("CLT").toLowerCase()}`;
  }
}

