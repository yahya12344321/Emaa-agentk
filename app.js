function averageVectors(vectors) {
  if (!vectors.length) return null;
  const length = Math.min(...vectors.map((vector) => vector.length));
  const average = new Array(length).fill(0);

  for (const vector of vectors) {
    for (let index = 0; index < length; index += 1) {
      average[index] += vector[index];
    }
  }

  for (let index = 0; index < length; index += 1) {
    average[index] = Number((average[index] / vectors.length).toFixed(5));
  }

  return average;
}

function vectorDistance(first, second) {
  const length = Math.min(first.length, second.length);
  if (!length) return 999;
  let total = 0;
  for (let index = 0; index < length; index += 1) {
    const delta = first[index] - second[index];
    total += delta * delta;
  }
  return Math.sqrt(total / length);
}

