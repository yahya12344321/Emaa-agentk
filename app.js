function softmaxVector(values) {
  let max = -Infinity;
  for (let index = 0; index < values.length; index += 1) {
    if (values[index] > max) max = values[index];
  }

  const probabilities = new Float32Array(values.length);
  let total = 0;
  for (let index = 0; index < values.length; index += 1) {
    const exponent = Math.exp(values[index] - max);
    probabilities[index] = exponent;
    total += exponent;
  }

  if (!total) return probabilities;
  for (let index = 0; index < probabilities.length; index += 1) {
    probabilities[index] /= total;
  }
  return probabilities;
}

